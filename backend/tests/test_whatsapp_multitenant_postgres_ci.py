def test_delivery_status_is_scoped_to_account_and_never_downgrades(wa_pg):
    for tenant, account, label in ((71,101,"A"), (72,202,"B")):
        stage_outbound_synthetic_intent(
            wa_pg, tenant_id=tenant, account_id=account,
            customer=SAME_GUEST, provider_message_id="same-outbound-provider-id")
    delivered = {"id": "same-outbound-provider-id", "status": "delivered"}
    assert ingest(wa_pg, envelope(statuses=[delivered]))["statuses"] == 1
    assert ingest(wa_pg, envelope(statuses=[{"id": delivered["id"],
                     "status": "sent"}]))["statuses"] == 0
    with wa_pg.connect() as db:
        statuses = db.execute(text("""
            SELECT tenant_id, delivery_status FROM public.wa_ci_messages
            ORDER BY tenant_id
        """)).all()
        assert [(r.tenant_id, r.delivery_status) for r in statuses] == [
            (71, "delivered"), (72, "pending")
        ]
    assert ingest(wa_pg, envelope(WABA_B, PHONE_B, statuses=[delivered]))["statuses"] == 1


def test_reactions_are_exact_account_scoped_and_idempotent(wa_pg):
    assert ingest(wa_pg, envelope(messages=[item("msg-a")]))["inbound"] == 1
    assert ingest(wa_pg, envelope(WABA_B, PHONE_B,
                 messages=[item("msg-b")]))["inbound"] == 1
    wrong = envelope(WABA_B, PHONE_B,
                     messages=[reaction("reaction-b", original="msg-a")])
    assert ingest(wa_pg, wrong)["reactions"] == 0
    correct = envelope(messages=[reaction("reaction-a", original="msg-a")])
    assert ingest(wa_pg, correct)["reactions"] == 1
    assert ingest(wa_pg, correct)["reactions"] == 0
    with wa_pg.connect() as db:
        rows = db.execute(text("""
            SELECT tenant_id, reaction_emoji FROM public.wa_ci_messages
            ORDER BY tenant_id
        """)).all()
        assert [(r.tenant_id, r.reaction_emoji) for r in rows] == [
            (71, "👍"), (72, None)
        ]
        assert db.execute(text("SELECT count(*) FROM public.wa_ci_reactions")).scalar_one() == 1



SECRET = "synthetic-whatsapp-ci-hmac-secret"
WABA_A, PHONE_A = "700000001", "800000001"
WABA_B, PHONE_B = "700000002", "800000002"
SAME_GUEST = "306900001111"


def item(mid, *, sender=SAME_GUEST, body="synthetic message"):
    return {"id": mid, "from": sender, "type": "text",
            "text": {"body": body}}


def reaction(mid, *, original, sender=SAME_GUEST, emoji="👍"):
    return {"id": mid, "from": sender, "type": "reaction",
            "reaction": {"message_id": original, "emoji": emoji}}


def envelope(waba=WABA_A, phone=PHONE_A, *, messages=None, statuses=None):
    value = {"metadata": {"phone_number_id": phone}}
    if messages is not None:
        value["messages"] = messages
    if statuses is not None:
        value["statuses"] = statuses
    return {"object": "whatsapp_business_account",
            "entry": [{"id": waba, "changes": [
                {"field": "messages", "value": value},
            ]}]}


def signed(payload, *, secret=SECRET):
    raw = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode()
    h = hmac.new(secret.encode(), raw, hashlib.sha256).hexdigest()
    return raw, "sha256=" + h


def ingest(engine, payload):
    raw, signature = signed(payload)
    return process_signed_synthetic_delivery(
        engine, raw, signature, app_secret=SECRET
    )


def count(engine, table):
    with engine.connect() as db:
        return db.execute(text("SELECT COUNT(*) FROM public." + table)).scalar_one()


